INSERT INTO public.competition_types (name)
SELECT min(btrim(cards.competition_type))
FROM public.cards
WHERE NULLIF(btrim(cards.competition_type), '') IS NOT NULL
  AND NOT EXISTS (
    SELECT 1
    FROM public.competition_types
    WHERE lower(public.competition_types.name) = lower(btrim(cards.competition_type))
  )
GROUP BY lower(btrim(cards.competition_type))
ON CONFLICT (name) DO NOTHING;

