CREATE TABLE IF NOT EXISTS public.circuit_types (
  name TEXT PRIMARY KEY CHECK (length(btrim(name)) > 0),
  sort_order BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

INSERT INTO public.circuit_types (name)
VALUES ('Route'), ('Urbain'), ('Oval')
ON CONFLICT (name) DO NOTHING;

UPDATE public.circuits
SET type = NULLIF(btrim(type), '')
WHERE type IS DISTINCT FROM NULLIF(btrim(type), '');

INSERT INTO public.circuit_types (name)
SELECT min(btrim(circuits.type))
FROM public.circuits
WHERE NULLIF(btrim(circuits.type), '') IS NOT NULL
  AND NOT EXISTS (
    SELECT 1
    FROM public.circuit_types
    WHERE lower(public.circuit_types.name) = lower(btrim(circuits.type))
  )
GROUP BY lower(btrim(circuits.type))
ON CONFLICT (name) DO NOTHING;

CREATE UNIQUE INDEX IF NOT EXISTS circuit_types_name_case_insensitive_idx
  ON public.circuit_types (lower(name));

UPDATE public.circuits
SET type = circuit_types.name
FROM public.circuit_types
WHERE lower(btrim(public.circuits.type)) = lower(circuit_types.name)
  AND public.circuits.type IS DISTINCT FROM circuit_types.name;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'circuits_type_fkey'
      AND conrelid = 'public.circuits'::regclass
  ) THEN
    ALTER TABLE public.circuits
      ADD CONSTRAINT circuits_type_fkey
      FOREIGN KEY (type)
      REFERENCES public.circuit_types (name)
      ON UPDATE CASCADE
      ON DELETE SET NULL;
  END IF;
END;
$$;

ALTER TABLE public.circuit_types ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Authenticated users read circuit types" ON public.circuit_types;
CREATE POLICY "Authenticated users read circuit types"
  ON public.circuit_types FOR SELECT TO authenticated
  USING (true);

DROP POLICY IF EXISTS "Admins insert circuit types" ON public.circuit_types;
CREATE POLICY "Admins insert circuit types"
  ON public.circuit_types FOR INSERT TO authenticated
  WITH CHECK (public.is_admin());

DROP POLICY IF EXISTS "Admins update circuit types" ON public.circuit_types;
CREATE POLICY "Admins update circuit types"
  ON public.circuit_types FOR UPDATE TO authenticated
  USING (public.is_admin())
  WITH CHECK (public.is_admin());

DROP POLICY IF EXISTS "Admins delete circuit types" ON public.circuit_types;
CREATE POLICY "Admins delete circuit types"
  ON public.circuit_types FOR DELETE TO authenticated
  USING (public.is_admin());

GRANT SELECT, INSERT, UPDATE, DELETE ON public.circuit_types TO authenticated;
