'use server';

import { revalidatePath } from 'next/cache';
import { getAdminAccess } from '@/lib/admin';
import { createServerSupabaseClient } from '@/lib/supabaseServer';
import { hasValidPlayerDeleteRequest, type PlayerAccount } from '@/lib/admin/playerDeletion';

type SearchResult = { success: true; players: PlayerAccount[] } | { success: false; error: string };
type DeleteResult = { success: true } | { success: false; error: string };

async function getOwnerClient() {
  const client = await createServerSupabaseClient();
  const { data: { user }, error } = await client.auth.getUser();
  if (error) return { client: null, ownerId: null, error: 'Impossible de vérifier ta session.' };
  if (!user) return { client: null, ownerId: null, error: 'Connecte-toi pour gérer les joueurs.' };

  const access = await getAdminAccess(client);
  if (access.error) return { client: null, ownerId: null, error: access.error };
  if (!access.isOwner) {
    return { client: null, ownerId: null, error: 'Seul le propriétaire du site peut supprimer un compte.' };
  }

  return { client, ownerId: user.id, error: null };
}

export async function searchPlayerAccounts(search: string): Promise<SearchResult> {
  if (typeof search !== 'string' || search.length > 100) {
    return { success: false, error: 'Recherche invalide (100 caractères maximum).' };
  }
  const auth = await getOwnerClient();
  if (!auth.client) return { success: false, error: auth.error ?? 'Accès refusé.' };

  const { data, error } = await auth.client.rpc('owner_search_player_accounts', {
    p_search: search.trim(),
    p_limit: 40,
  });
  if (error) {
    console.error('[AdminPlayers] Recherche impossible:', error.message);
    return { success: false, error: 'Impossible de charger les joueurs. Vérifie la migration 043.' };
  }
  return { success: true, players: (data ?? []) as PlayerAccount[] };
}

export async function permanentlyDeletePlayerAccount(
  userId: string,
  expectedUsername: string,
  expectedEmail: string,
  confirmation: string,
): Promise<DeleteResult> {
  if (!hasValidPlayerDeleteRequest(userId, expectedUsername, expectedEmail, confirmation)) {
    return { success: false, error: 'Confirmation invalide. Saisis exactement la phrase demandée.' };
  }

  const auth = await getOwnerClient();
  if (!auth.client || !auth.ownerId) {
    return { success: false, error: auth.error ?? 'Accès refusé.' };
  }
  if (userId === auth.ownerId) {
    return { success: false, error: 'Tu ne peux pas supprimer ton compte propriétaire.' };
  }

  // The RPC repeats owner authorization, reassigns any delegated admin grants,
  // and verifies the immutable UUID and stored username/email in one transaction.
  const { data, error } = await auth.client.rpc('permanently_delete_player_account', {
    p_user_id: userId,
    p_expected_username: expectedUsername,
    p_expected_email: expectedEmail,
    p_confirmation: confirmation,
  });

  if (error) {
    console.error('[AdminPlayers] Suppression interrompue:', error.message);
    // Error text is generated by our protected RPC, not accepted from a client.
    return { success: false, error: error.message };
  }
  if (!data?.success) {
    return { success: false, error: 'Suppression non confirmée par Supabase.' };
  }

  revalidatePath('/admin/players');
  revalidatePath('/leaderboard');
  revalidatePath('/marketplace');
  return { success: true };
}
