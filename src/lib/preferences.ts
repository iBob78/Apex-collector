export function translate(language: SiteLanguage, message: string, values?: Record<string, string | number>) {
  const translated = messages[language][message] ?? message;
  return values
    ? translated.replace(/\{(\w+)\}/g, (match, key: string) => String(values[key] ?? match))
    : translated;
}

export function formatSpeed(value: number, units: UnitSystem, language: SiteLanguage = 'fr') {
  return units === 'imperial'
    ? `${new Intl.NumberFormat(language, { maximumFractionDigits: 0 }).format(value * 0.621371)} mph`
    : `${new Intl.NumberFormat(language, { maximumFractionDigits: 0 }).format(value)} km/h`;
}

export function formatPower(powerHp: number, units: UnitSystem, language: SiteLanguage = 'fr', powerKw?: number | null) {
  return units === 'metric'
    ? `${new Intl.NumberFormat(language, { maximumFractionDigits: 0 }).format(powerKw != null ? powerKw * 1.35962 : powerHp * 1.01387)} CV`
    : `${new Intl.NumberFormat(language, { maximumFractionDigits: 0 }).format(powerHp)} HP`;
}

export function formatTorque(value: number, units: UnitSystem, language: SiteLanguage = 'fr') {
  return units === 'imperial'
    ? `${new Intl.NumberFormat(language, { maximumFractionDigits: 0 }).format(value * 0.737562)} lb-ft`
    : `${new Intl.NumberFormat(language, { maximumFractionDigits: 0 }).format(value)} Nm`;
}

export function formatWeight(value: number, units: UnitSystem, language: SiteLanguage = 'fr') {
  if (units === 'imperial') {
    const pounds = value > 50 ? value * 2.20462 : value * 2204.62;
    return `${new Intl.NumberFormat(language, { maximumFractionDigits: 0 }).format(pounds)} lb`;
  }
  const kilograms = value > 50 ? value : value * 1000;
  return `${new Intl.NumberFormat(language, { maximumFractionDigits: 0 }).format(kilograms)} kg`;
}

export function formatDistance(value: number, units: UnitSystem, language: SiteLanguage = 'fr') {
  return units === 'imperial'
    ? `${new Intl.NumberFormat(language, { maximumFractionDigits: 1 }).format(value * 0.621371)} mi`
    : `${new Intl.NumberFormat(language, { maximumFractionDigits: 1 }).format(value)} km`;
}
